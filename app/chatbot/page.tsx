// ── Calorie helper ────────────────────────────────────────────────────────────
function estimateCalories(weightStr = '80', activityStr = '') {
  const w = parseInt(weightStr) || 80
  const active = activityStr.toLowerCase().includes('active')
  return active ? w * 32 : w * 27
}

