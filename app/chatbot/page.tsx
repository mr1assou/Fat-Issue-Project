type Message = ReturnType<typeof useAppSelector> extends never ? never : {
  id: string
  role: 'user' | 'assistant'
  content: string
  timestamp: number
  type?: 'text' | 'plan' | 'paywall' | 'upgrade' | 'upsell'
}
